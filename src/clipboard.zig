//! Opt-in NSPasteboard polling, independent of the launcher window. AppKit
//! reads run on the main run loop (as in Maccy's public Clipboard.swift).
//! Stop invalidates the timer before freeing any state. No Accessibility
//! permission is needed until the paste action.
//! References: https://www.alfredapp.com/help/features/clipboard/ and
//! https://github.com/p0deje/Maccy/blob/master/Maccy/Clipboard.swift
const std = @import("std");
const objc = @import("nanoui").objc;
pub const history = @import("clipboard_store.zig");
pub const Store = history.Store;

const interval_s = 0.5;
const epoch_offset = 978307200;

/// Password managers use ConcealedType. Transient/generated content follows
/// Maccy's ignore policy as well. Check types before requesting any payload.
pub fn ignoredType(t: []const u8) bool {
    for ([_][]const u8{
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
    }) |ignored| if (std.mem.eql(u8, ignored, t)) return true;
    return false;
}

/// Owns the store and its directory. Initialize freely; start is the only
/// operation that reads NSPasteboard or opens Application Support. Keep at
/// a stable address, and call every method on the main thread.
pub const Capture = struct {
    store: Store,
    io: std.Io,
    home: ?[]const u8,
    dir: ?std.Io.Dir = null,
    timer: ?*anyopaque = null,
    change_count: objc.NSInteger = 0,
    last_prune: i64 = 0,
    warned: bool = false,
    changed: ?struct { ctx: *anyopaque, func: *const fn (*anyopaque) void } = null,

    pub fn enabled(c: *const Capture) bool {
        return c.timer != null;
    }

    pub fn start(c: *Capture) !void {
        if (c.enabled()) return;
        if (c.dir == null) {
            const home = c.home orelse return error.HomeUnavailable;
            const path = try std.fmt.allocPrint(c.store.gpa, "{s}/Library/Application Support/Nanolight/Clipboard", .{home});
            defer c.store.gpa.free(path);
            const dir = try std.Io.Dir.cwd().createDirPathOpen(c.io, path, .{ .permissions = .fromMode(0o700), .open_options = .{ .iterate = true } });
            errdefer dir.close(c.io);
            try dir.setPermissions(c.io, .fromMode(0o700));
            try c.store.load(c.io, dir, now());
            c.dir = dir;
        }
        _ = c.store.prune(now());
        try c.flush();
        const pool = objc.Pool.push();
        defer pool.pop();
        // Enabling/resuming starts at the current changeCount. Content from
        // before consent, or copied while disabled, is never imported.
        const pb = pasteboard();
        c.change_count = objc.msg(objc.NSInteger, pb, "changeCount", .{});
        c.last_prune = now();
        var context: TimerContext = .{ .info = c };
        const timer = CFRunLoopTimerCreate(null, CFAbsoluteTimeGetCurrent() + interval_s, interval_s, 0, 0, tick, &context) orelse return error.TimerUnavailable;
        c.timer = timer;
        CFRunLoopAddTimer(CFRunLoopGetMain(), timer, kCFRunLoopCommonModes);
    }

    pub fn stop(c: *Capture) void {
        if (c.timer) |timer| {
            CFRunLoopTimerInvalidate(timer);
            CFRelease(timer);
            c.timer = null;
        }
        c.flush() catch |e| c.warn(e);
    }

    pub fn deinit(c: *Capture) void {
        c.stop();
        if (c.dir) |dir| dir.close(c.io);
        c.store.deinit();
    }

    /// Also used after delete/clear/pin actions. Failed writes leave
    /// dirty set and are retried by the next tick; never log copied content.
    pub fn flush(c: *Capture) !void {
        if (c.dir) |dir| try c.store.save(c.io, dir);
        c.warned = false;
    }

    /// Restore the original representation, and don't capture our own write.
    pub fn restore(c: *Capture, id: u64) !void {
        const item = c.store.get(id) orelse return error.ItemExpired;
        const pb = pasteboard();
        try writeItem(pb, item);
        c.change_count = objc.msg(objc.NSInteger, pb, "changeCount", .{});
    }

    fn warn(c: *Capture, err: anyerror) void {
        if (!c.warned) std.log.warn("nanolight: clipboard history ({s})", .{@errorName(err)});
        c.warned = true;
    }

    fn tick(_: *anyopaque, ctx: ?*anyopaque) callconv(.c) void {
        const c: *Capture = @ptrCast(@alignCast(ctx.?));
        if (!c.enabled()) return;
        const pool = objc.Pool.push();
        defer pool.pop();
        const time = now();
        // Expire history even when nobody copies anything.
        if (time - c.last_prune >= 60 or time < c.last_prune) {
            _ = c.store.prune(time);
            c.last_prune = time;
        }
        c.poll(pasteboard(), time) catch |e| c.warn(e);
        if (c.store.dirty) if (c.changed) |h| h.func(h.ctx);
        c.flush() catch |e| c.warn(e);
    }

    fn poll(c: *Capture, pb: objc.Object, time: i64) !void {
        const count = objc.msg(objc.NSInteger, pb, "changeCount", .{});
        if (count == c.change_count) return;
        c.change_count = count;
        if (concealed(pb)) return;
        const items = objc.msg(?objc.Object, pb, "pasteboardItems", .{}) orelse return;
        var arena: std.heap.ArenaAllocator = .init(c.store.gpa);
        defer arena.deinit();
        var copies: std.ArrayList(Copy) = .empty;
        var bytes: usize = 0;
        for (0..objc.msg(objc.NSUInteger, items, "count", .{})) |i| {
            const item = objc.msg(objc.Object, items, "objectAtIndex:", .{i});
            if (concealed(item)) return;
            if (copies.items.len >= c.store.limits.max_items) break;
            const budget = @min(c.store.limits.max_item_bytes, c.store.limits.max_bytes - bytes);
            if (try read(arena.allocator(), item, budget)) |copy| {
                try copies.append(arena.allocator(), copy);
                bytes += copy.data.len;
            }
        }
        // A lazy pasteboard provider may change the board during a read.
        // Discard the entire snapshot and retry the new count next tick.
        if (objc.msg(objc.NSInteger, pb, "changeCount", .{}) != count or concealed(pb)) return;
        for (copies.items) |copy| _ = try c.store.add(copy.kind, copy.data, time);
    }
};

/// Public NSPasteboard formats only. File URLs use an item, like Maccy;
/// image bytes aren't transcoded or reduced to their display label.
fn writeItem(pb: objc.Object, item: history.Item) !void {
    const name = objc.nsString(switch (item.kind) {
        .text => "public.utf8-plain-text",
        .png => "public.png",
        .tiff => "public.tiff",
        .file_url => "public.file-url",
    });
    const entry = objc.msg(objc.Object, objc.class("NSPasteboardItem"), "new", .{});
    defer objc.msg(void, entry, "release", .{});
    const data = objc.msg(objc.Object, objc.class("NSData"), "dataWithBytes:length:", .{ item.data.ptr, @as(objc.NSUInteger, item.data.len) });
    if (!objc.msg(objc.BOOL, entry, "setData:forType:", .{ data, name })) return error.PasteboardWriteFailed;
    const entries = objc.msg(objc.Object, objc.class("NSArray"), "arrayWithObject:", .{entry});
    _ = objc.msg(objc.NSInteger, pb, "clearContents", .{});
    if (!objc.msg(objc.BOOL, pb, "writeObjects:", .{entries})) return error.PasteboardWriteFailed;
}

const Copy = struct { kind: history.Kind, data: []const u8 };

fn read(gpa: std.mem.Allocator, item: objc.Object, max_bytes: usize) !?Copy {
    // One primary representation per item. Preserve PNG/TIFF as-is; a file
    // URL records the link, without reading or copying the referenced file.
    const types = [_]struct { history.Kind, []const u8 }{
        .{ .file_url, "public.file-url" },
        .{ .png, "public.png" },
        .{ .tiff, "public.tiff" },
        .{ .text, "public.utf8-plain-text" },
    };
    const offered = objc.msg(?objc.Object, item, "types", .{}) orelse return null;
    for (types) |t| {
        const name = objc.nsString(t[1]);
        if (!objc.msg(objc.BOOL, offered, "containsObject:", .{name})) continue;
        const data = objc.msg(?objc.Object, item, "dataForType:", .{name}) orelse continue;
        const len = objc.msg(objc.NSUInteger, data, "length", .{});
        if (len == 0 or len > max_bytes) continue;
        const bytes = objc.msg(?[*]const u8, data, "bytes", .{}) orelse continue;
        return .{ .kind = t[0], .data = try gpa.dupe(u8, bytes[0..len]) };
    }
    return null;
}

fn concealed(item: objc.Object) bool {
    const types = objc.msg(?objc.Object, item, "types", .{}) orelse return false;
    for (0..objc.msg(objc.NSUInteger, types, "count", .{})) |i| {
        const t = objc.msg(objc.Object, types, "objectAtIndex:", .{i});
        if (ignoredType(objc.fromNSString(t))) return true;
    }
    return false;
}

fn pasteboard() objc.Object {
    return objc.msg(objc.Object, objc.class("NSPasteboard"), "generalPasteboard", .{});
}

fn now() i64 {
    return @intFromFloat(CFAbsoluteTimeGetCurrent() + epoch_offset);
}

const TimerContext = extern struct {
    version: isize = 0,
    info: ?*anyopaque,
    retain: ?*const anyopaque = null,
    release: ?*const anyopaque = null,
    copy_description: ?*const anyopaque = null,
};
extern "c" fn CFAbsoluteTimeGetCurrent() f64;
extern "c" fn CFRunLoopGetMain() *anyopaque;
extern "c" const kCFRunLoopCommonModes: *const anyopaque;
extern "c" fn CFRunLoopTimerCreate(?*anyopaque, f64, f64, usize, isize, *const fn (*anyopaque, ?*anyopaque) callconv(.c) void, *TimerContext) ?*anyopaque;
extern "c" fn CFRunLoopAddTimer(*anyopaque, *anyopaque, *const anyopaque) void;
extern "c" fn CFRunLoopTimerInvalidate(*anyopaque) void;
extern "c" fn CFRelease(*anyopaque) void;

test "clipboard ignores privacy and transient markers, not ordinary formats" {
    const t = std.testing;
    try t.expect(ignoredType("org.nspasteboard.ConcealedType"));
    try t.expect(ignoredType("org.nspasteboard.TransientType"));
    try t.expect(ignoredType("org.nspasteboard.AutoGeneratedType"));
    try t.expect(ignoredType("de.petermaurer.TransientPasteboardType"));
    try t.expect(!ignoredType("public.utf8-plain-text"));
    try t.expect(!ignoredType("public.png"));
}

test "restoring every stored representation preserves bytes on a private board" {
    const t = std.testing;
    const pool = objc.Pool.push();
    defer pool.pop();
    const pb = objc.msg(objc.Object, objc.class("NSPasteboard"), "pasteboardWithUniqueName", .{});
    defer objc.msg(void, pb, "releaseGlobally", .{});
    const kinds = [_]history.Kind{ .text, .png, .tiff, .file_url };
    const types = [_][]const u8{ "public.utf8-plain-text", "public.png", "public.tiff", "public.file-url" };
    const payloads = [_][]const u8{ "original\n文本", "\x89PNG\x00\xff", "II\x2a\x00\xff", "file:///tmp/test%20file.txt" };
    for (kinds, types, payloads) |kind, name, payload| {
        try writeItem(pb, .{ .id = 1, .copied_at = 100, .kind = kind, .data = payload });
        const data = objc.msg(?objc.Object, pb, "dataForType:", .{objc.nsString(name)}) orelse return error.MissingRepresentation;
        const len = objc.msg(objc.NSUInteger, data, "length", .{});
        const bytes = objc.msg([*]const u8, data, "bytes", .{});
        try t.expectEqualStrings(payload, bytes[0..len]);
    }
}

test "pasteboard polling captures text and image bytes and skips concealed snapshots" {
    const t = std.testing;
    const pool = objc.Pool.push();
    defer pool.pop();
    // A private board, never the user's general clipboard. No app/window or
    // Application Support directory is created by this test.
    const pb = objc.msg(objc.Object, objc.class("NSPasteboard"), "pasteboardWithUniqueName", .{});
    defer objc.msg(void, pb, "releaseGlobally", .{});
    var c: Capture = .{ .store = .init(t.allocator), .io = t.io, .home = null };
    defer c.deinit();
    _ = objc.msg(objc.NSInteger, pb, "clearContents", .{});
    _ = objc.msg(objc.BOOL, pb, "setString:forType:", .{ objc.nsString("hello"), objc.nsString("public.utf8-plain-text") });
    c.change_count = objc.msg(objc.NSInteger, pb, "changeCount", .{});
    // The enabling baseline must not import preexisting clipboard content.
    try c.poll(pb, 100);
    try t.expectEqual(@as(usize, 0), c.store.items.items.len);
    _ = objc.msg(objc.NSInteger, pb, "clearContents", .{});
    _ = objc.msg(objc.BOOL, pb, "setString:forType:", .{ objc.nsString("hello"), objc.nsString("public.utf8-plain-text") });
    try c.poll(pb, 101);
    try t.expectEqualStrings("hello", c.store.items.items[0].data);
    try c.poll(pb, 102);
    try t.expectEqual(@as(i64, 101), c.store.items.items[0].copied_at);
    // A second copy of identical content updates rather than appends.
    _ = objc.msg(objc.NSInteger, pb, "clearContents", .{});
    _ = objc.msg(objc.BOOL, pb, "setString:forType:", .{ objc.nsString("hello"), objc.nsString("public.utf8-plain-text") });
    try c.poll(pb, 103);
    try t.expectEqual(@as(usize, 1), c.store.items.items.len);
    try t.expectEqual(@as(i64, 103), c.store.items.items[0].copied_at);
    _ = objc.msg(objc.NSInteger, pb, "clearContents", .{});
    _ = objc.msg(objc.BOOL, pb, "setString:forType:", .{ objc.nsString("secret"), objc.nsString("public.utf8-plain-text") });
    _ = objc.msg(objc.BOOL, pb, "setString:forType:", .{ objc.nsString(""), objc.nsString("org.nspasteboard.ConcealedType") });
    try c.poll(pb, 104);
    try t.expectEqual(@as(usize, 1), c.store.items.items.len);
    const image = "\x89PNG\x00\xff\x80";
    const data = objc.msg(objc.Object, objc.class("NSData"), "dataWithBytes:length:", .{ image.ptr, @as(objc.NSUInteger, image.len) });
    _ = objc.msg(objc.NSInteger, pb, "clearContents", .{});
    _ = objc.msg(objc.BOOL, pb, "setData:forType:", .{ data, objc.nsString("public.png") });
    try c.poll(pb, 105);
    try t.expectEqual(@as(usize, 2), c.store.items.items.len);
    try t.expectEqual(history.Kind.png, c.store.items.items[0].kind);
    try t.expectEqualStrings(image, c.store.items.items[0].data);
    // An unsupported copy doesn't insert an empty placeholder.
    _ = objc.msg(objc.NSInteger, pb, "clearContents", .{});
    _ = objc.msg(objc.BOOL, pb, "setString:forType:", .{ objc.nsString("opaque"), objc.nsString("dev.nanoui.unsupported-test-type") });
    try c.poll(pb, 106);
    try t.expectEqual(@as(usize, 2), c.store.items.items.len);
    try t.expect(!c.enabled());
}
